import logging
from typing import List, Optional, Literal
from pydantic import BaseModel, Field
from fastapi import FastAPI
from langchain.messages import SystemMessage, HumanMessage
from langgraph.types import interrupt
from langgraph.graph import END, START, MessagesState, StateGraph
from dependencies import ConnectLLM, load_prompt, get_checkpointer
from userrepo import save_section

# Setup
logger = logging.getLogger(__name__)
llm = ConnectLLM()

# --- 1. State and Models ---

class SkillState(MessagesState):
    raw_skills_input: str
    refinement_questions: List[str]  # Questions generated by the LLM
    user_answers: dict[str, str]     # Answers provided by the user
    drafts: List[str]                # History of skill block drafts
    refinements: List[str]           # Feedback requests from the user
    approved: bool                   # Approval flag
    current_stage: str
    refinement_counts: int
    session_id: str

class SkillsPayload(BaseModel):
    skills_raw: str
    is_approved: bool

# --- 2. Graph Nodes ---

def CallLLM(state: SkillState):
    """Analyzes raw skills and generates clarifying questions to find missing gaps."""
    system_prompt = load_prompt(r"prompts\SkillFlow\machinequeries.txt")
    
    context = f"User's Raw Skills Input: {state.get('raw_skills_input', '')}"
    
    # In a real app, use with_structured_output to force a JSON list of questions
    result = llm.invoke([SystemMessage(content=system_prompt), HumanMessage(content=context)])
    
    # Mocking the parsed list for this example
    questions = [q.strip() for q in result.content.split('\n') if q.strip()]
    
    return {
        "refinement_questions": questions,
        "current_stage": "questions_generated"
    }

def AskQuestions(state: SkillState):
    """Pauses the graph to send questions to the user and wait for their answers."""
    # Interrupt pauses the graph and sends payload to the UI
    user_response = interrupt({
        "action": "answer_questions",
        "questions": state.get("refinement_questions", [])
    })
    
    return {
        "user_answers": user_response.get("answers", {}),
        "current_stage": "answers_collected"
    }

def PrepareDraft(state: SkillState):
    """Compiles the raw skills, user answers, and any refinements into a structured Skill Block."""
    system_prompt = load_prompt(r"prompts\SkillFlow\initial_draft.txt")
    
    last_refinement = state["refinements"][-1] if state.get("refinements") else "None"
    
    context = f"""
    Raw Skills: {state.get('raw_skills_input', '')}
    User Q&A Context: {state.get('user_answers', {})}
    User's Refinement Request (if any): {last_refinement}
    """
    
    result = llm.invoke([SystemMessage(content=system_prompt), HumanMessage(content=context)])
    
    return {
        "drafts": state.get("drafts", []) + [result.content],
        "current_stage": "draft_prepared"
    }

def PresentForReview(state: SkillState):
    """Pauses the graph to show the drafted skill block to the user for approval."""
    latest_draft = state.get("drafts", ["No draft available"])[-1]
    
    # Interrupt asks the UI to show the draft and return an approval boolean
    review_response = interrupt({
        "action": "review_draft",
        "latest_draft": latest_draft
    })
    
    return {
        "approved": review_response.get("approved", False),
        "current_stage": "reviewed"
    }

def Refine(state: SkillState) -> Literal["StoreDB", "AskRefinements"]:
    """Conditional Edge: Routes based on user approval."""
    if state.get("approved", False):
        return "StoreDB"
    return "AskRefinements"

def AskRefinements(state: SkillState):
    """Pauses the graph to ask the user exactly WHAT they want to change about the rejected draft."""
    refinement_response = interrupt({
        "action": "request_refinement_feedback",
        "message": "What would you like to change or improve in this skill list?"
    })
    
    existing_refinements = state.get("refinements", [])
    counts = state.get("refinement_counts", 0)
    
    return {
        "refinements": existing_refinements + [refinement_response.get("feedback", "")],
        "refinement_counts": counts + 1,
        "current_stage": "refinement_requested"
    }

def StoreDB(state: SkillState):
    """Saves the final approved skill block to the database."""
    final_draft = state["drafts"][-1] if state.get("drafts") else ""
    is_approved = state.get("approved", False)
    
    payload = SkillsPayload(skills_raw=final_draft, is_approved=is_approved)
    save_section(state['session_id'], "skills", payload.model_dump())
    
    return {"current_stage": "Completed"}


# --- 3. Graph Builder ---

def build_skills_graph():
    graph = StateGraph(SkillState)
    
    # Add Nodes
    graph.add_node("CallLLM", CallLLM)
    graph.add_node("AskQuestions", AskQuestions)
    graph.add_node("PrepareDraft", PrepareDraft)
    graph.add_node("PresentForReview", PresentForReview)
    graph.add_node("AskRefinements", AskRefinements)
    graph.add_node("StoreDB", StoreDB)
    
    # Add Edges (Following your exact defined flow)
    graph.add_edge(START, "CallLLM")
    graph.add_edge("CallLLM", "AskQuestions")
    graph.add_edge("AskQuestions", "PrepareDraft")
    graph.add_edge("PrepareDraft", "PresentForReview")
    
    # Conditional Routing
    graph.add_conditional_edges("PresentForReview", Refine, { 
        "StoreDB": "StoreDB",
        "AskRefinements": "AskRefinements"
    })
    
    # The Loop Back
    graph.add_edge("AskRefinements", "PrepareDraft") # Skips generating questions again, goes straight to redrafting
    graph.add_edge("StoreDB", END)
    
    return graph

# Build and compile ONCE at import time
skills_app = build_skills_graph().compile(checkpointer=get_checkpointer())